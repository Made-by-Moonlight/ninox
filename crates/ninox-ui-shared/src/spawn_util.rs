//! Shared spawn plumbing used by both the CLI worker path (`main.rs
//! run_spawn`) and the in-app standalone spawn (`app.rs SpawnFormConfirm`):
//! isolated worktree creation, repo-slug detection, tilde expansion, and the
//! interactive tmux+PTY launch sequence shared by both spawn-modal kinds.

use std::sync::Arc;
use std::time::Duration;

use ninox_core::{
    events::Engine, pty, runtime, session_socket::CLAUDE_MESSAGING_GATE_ENV, store::Store, Event,
    Session, SessionFields, SessionStatus,
};

/// The per-kind differences between the spawn-modal launch paths
/// (standalone vs orchestrator). Everything else — env resolution,
/// PATH-prepend launch command, tmux session creation, pid lookup,
/// session persistence, and PTY streaming — is identical and lives in
/// [`spawn_interactive_session`].
pub struct InteractiveSpawnParams {
    /// Session id; also used as the tmux session name.
    pub session_id:      String,
    pub name:            String,
    /// Directory the agent starts in (isolated worktree for standalone,
    /// per-orchestrator subdirectory for orchestrators). Recorded as the
    /// session's `workspace_path`.
    pub workspace:       String,
    /// GitHub `owner/repo` slug ("" when unknown / not applicable).
    pub repo:            String,
    pub orchestrator_id: Option<String>,
    pub agent:           ninox_core::config::AgentConfig,
    /// Resolved interactive launch command (registry-resolved by the
    /// caller: `AppConfig::registry().interactive_cmd(&agent)`). Kept
    /// separate from `agent` so this module needs no registry access;
    /// `agent` remains for session-record stamping (agent_type/model).
    pub base_cmd:        String,
    /// Exported as `NINOX_BRAIN` (write path) + `NINOX_BRAIN_READS` and
    /// recorded on the session row. `None` leaves both unset, so the
    /// session falls back to the default set.
    pub brain:           Option<ninox_core::brain_set::BrainSet>,
    /// Extra env pairs beyond the shared NINOX_BIN/NINOX_CONFIG/NINOX_BRAIN
    /// (e.g. NINOX_ORCHESTRATOR_ID + caller-type vars for orchestrators).
    pub extra_env:       Vec<(String, String)>,
    pub started_at:      i64,
    /// UUID for `--session-id`/`--resume` (see `ninox_core::harness::new_claude_session_id`).
    /// Generated by the caller — this module never generates one itself,
    /// so `Re-file` (Task 8) can mint a fresh id while Resume (Task 10)
    /// reuses the session's existing one.
    pub claude_session_id: String,
    /// Status to set if `tmux::create_session` fails. `Terminated` for a
    /// fresh spawn or Re-file (nothing worth preserving); `Interrupted`
    /// for Resume (keep it retryable — see the design spec's Error
    /// Handling section).
    pub failure_status:  ninox_core::SessionStatus,
    /// One-line task summary carried over from the session being
    /// respawned (Re-file/Resume); `None` for a fresh spawn, which has no
    /// prior summary to preserve.
    pub summary:         Option<String>,
    /// The mode `base_cmd` was built with, recorded on the row so every
    /// later relaunch resumes in it (see `restart::session_permission_mode`).
    pub permission_mode: ninox_core::harness::PermissionMode,
}

/// Launch an interactive agent session inside tmux and start PTY streaming.
///
/// On success, returns the tmux attach argv for the new session so the
/// caller can emit `Message::ClientAttach` and render it immediately at the
/// right size (the attached-client flow sizes the PTY to the real panel).
/// On tmux failure (e.g. the workspace path is bad) the session is marked
/// with the caller-supplied `p.failure_status` in the store (`Terminated`
/// for a fresh spawn or Re-file, `Interrupted` for Resume — see
/// `InteractiveSpawnParams::failure_status`), a `SessionUpdated` event is
/// emitted so the UI reflects the new status instead of a session stuck in
/// Working forever, and the failure's cause is returned as one line for the
/// UI to show.
pub async fn spawn_interactive_session(
    engine: Arc<Engine>,
    p: InteractiveSpawnParams,
) -> Result<Vec<String>, String> {
    launch_interactive_session(engine, p, true).await
}

/// [`spawn_interactive_session`] with PTY streaming optional: a short-lived
/// CLI process (`ninox fleet restore`) must not pipe the pane into a FIFO
/// that dies with it.
pub async fn launch_interactive_session(
    engine: Arc<Engine>,
    p: InteractiveSpawnParams,
    stream_pty: bool,
) -> Result<Vec<String>, String> {
    let sid = p.session_id;

    let ninox_bin = ninox_core::hooks::canonical_exe()
        .ok()
        .and_then(|x| x.to_str().map(str::to_string))
        .unwrap_or_else(|| "ninox".to_string());
    let ninox_config = ninox_core::config::AppConfig::config_path()
        .to_string_lossy()
        .to_string();
    // Session metadata dir — must be set for both Orchestrator and Standalone
    // kinds, mirroring the CLI worker path (`main.rs run_spawn`). Without
    // these, the gh/git wrapper scripts (`ninox_core::hooks`) have nowhere to
    // record PR/branch metadata for app-spawned sessions, and the usage
    // poller has no session id to attribute cost/token ingestion to.
    let sessions_dir = ninox_core::config::AppConfig::sessions_dir();
    std::fs::create_dir_all(&sessions_dir).ok();
    let sessions_dir_str = sessions_dir.to_string_lossy().to_string();

    // Opt-in per-repo shared build cache (e.g. a shared sccache wrapper) —
    // see `ninox_core::config::WorkspacesConfig`. On a blocking thread: this
    // reads config.toml from disk and may probe PATH for `sccache` via a
    // child process, neither of which should stall this runtime's other
    // concurrent sessions (same reasoning as `seed_workspace_trust` above).
    let shared_build_workspace = p.workspace.clone();
    let shared_build_env = tokio::task::spawn_blocking(ninox_core::test_isolation::propagate(move || {
        ninox_core::config::AppConfig::load_or_default()
            .workspaces
            .effective_shared_build_env_for(std::path::Path::new(&shared_build_workspace))
    }))
    .await
    .unwrap_or_default();
    let mut extra_env = p.extra_env.clone();
    extra_env.extend(shared_build_env);
    let brain_write = p.brain.as_ref().map(|b| b.write_str()).unwrap_or_default();
    let brain_reads = p.brain.as_ref().map(|b| b.reads_env_value()).unwrap_or_default();
    let env = interactive_env_vars(
        &ninox_bin, &ninox_config, &brain_write, &brain_reads, &sid, &sessions_dir_str, &extra_env,
    );

    let launch_cmd = ninox_core::hooks::with_bin_dir_on_path(&p.base_cmd);

    // Without a trust entry the session blocks forever on Claude Code's
    // "do you trust this folder?" dialog instead of reaching its input
    // prompt (fresh orchestrator workspaces and worker worktrees have none).
    // On a blocking thread for the same reason as `create_worker_worktree`:
    // this reads and rewrites the user's whole ~/.claude.json (hundreds of
    // KB of accumulated per-project state) and would stall a runtime worker.
    let trust_ws = p.workspace.clone();
    let seed = tokio::task::spawn_blocking(move || {
        ninox_core::trust::seed_workspace_trust(std::path::Path::new(&trust_ws))
    })
    .await;
    if let Err(e) = seed.unwrap_or_else(|join_err| Err(anyhow::anyhow!(join_err))) {
        tracing::warn!("failed to seed claude workspace trust for {}: {e}", p.workspace);
    }

    if let Err(e) = runtime::create_session(runtime::configured_backend(), &sid, &p.workspace, &launch_cmd, &env).await {
        tracing::error!("session create failed for {sid}: {e}");
        // Surface the failure: without this the optimistically inserted
        // session would sit in Working forever.
        if let Ok(Some(mut s)) = engine.store.get_session(&sid) {
            s.status = p.failure_status;
            let _ = engine.store.upsert_session(&s);
            engine.emit(Event::SessionUpdated(s, SessionFields::STATUS));
        }
        return Err(format!("{e:#}"));
    }

    tokio::time::sleep(tokio::time::Duration::from_millis(300)).await;

    let pid = runtime::session_pid(&sid).await;

    // Resume and Re-file respawn an *existing* row — carry forward every
    // field the spawn isn't authoritative for (PR linkage, gate breakdown,
    // accumulated cost, context readout) instead of hardcoding it empty,
    // which wiped all of them from both the store and (via the ALL-flagged
    // emit below) app memory until the pollers re-derived them. A fresh
    // spawn's optimistically-inserted row holds exactly these empty values
    // anyway, so carrying them forward is a no-op there. Read the row here
    // — after the awaits above, with none between read and write — so the
    // ALL emit's payload is fresh by construction. `terminal_at` is NOT
    // carried: the session is back to Working, so the retention countdown
    // ends.
    let prior = engine.store.get_session(&sid).ok().flatten();
    let prior = prior.as_ref();
    let resumed = prior.and_then(|s| s.claude_session_id.as_deref()) == Some(p.claude_session_id.as_str());
    let updated = Session {
        id:              sid.clone(),
        orchestrator_id: p.orchestrator_id,
        name:            p.name,
        repo:            p.repo,
        status:          SessionStatus::Working,
        agent_type:      p.agent.harness.clone(),
        cost_usd:        prior.map_or(0.0, |s| s.cost_usd),
        started_at:      p.started_at,
        pr_number:       prior.and_then(|s| s.pr_number),
        pr_id:           prior.and_then(|s| s.pr_id),
        workspace_path:  Some(p.workspace),
        pid,
        model:           p.agent.model.clone(),
        context_tokens:  prior.and_then(|s| s.context_tokens),
        brain_reads:     p.brain.as_ref().map(|b| {
            b.reads.iter().map(|r| r.to_string_lossy().into_owned()).collect()
        }).unwrap_or_default(),
        brain_write:     p.brain.as_ref().map(|b| b.write_str()),
        context_used_pct:     prior.and_then(|s| s.context_used_pct),
        context_total_tokens: prior.and_then(|s| s.context_total_tokens),
        context_window_size:  prior.and_then(|s| s.context_window_size),
        claude_session_id: Some(p.claude_session_id),
        summary:         p.summary,
        terminal_at:     None,
        // Carried so a resumed session whose PR already merged doesn't
        // re-fire merge detection (a duplicate notification — or, with
        // `[auto_reap]` on, an instant cleanup of the row just respawned).
        merged_at:       prior.and_then(|s| s.merged_at),
        gate_status:     prior.and_then(|s| s.gate_status.clone()),
        // Activity is NOT carried: a respawn is a fresh agent incarnation,
        // so a prior Blocked/note would lie until the new incarnation's
        // first hook fires. Unknown is the honest interim value.
        activity:        Default::default(),
        activity_note:   None,
        activity_since:  None,
        // Carried: a respawn/resume is still the same session on whatever
        // machine spawned it — hardcoding `None` here would silently wipe a
        // remote session's machine affiliation back to "local".
        machine_id:      prior.and_then(|s| s.machine_id.clone()),
        // Carried: a respawn/resume is still the same worker-type
        // incarnation, not a fresh untyped spawn.
        worker_type:     prior.and_then(|s| s.worker_type.clone()),
        success_criteria: Vec::new(),
        completion_outcome: None,
        self_completed_at: None,
        // Not carried: this incarnation hasn't been cleaned up.
        cleanup_result:  None,
        cleanup_at:      None,
    };
    let _ = engine.store.upsert_session(&updated);
    if let Err(e) = engine.store.set_permission_mode(&sid, p.permission_mode) {
        tracing::warn!("record permission mode for {sid}: {e}");
    }
    engine.emit(Event::SessionUpdated(updated, SessionFields::ALL));
    let now = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_millis() as i64);
    ninox_core::fleet::note_relaunch(&engine.store, &sid, resumed, now);

    if stream_pty {
        if let Err(e) = pty::start_streaming(engine.clone(), sid.clone(), &sid).await {
            tracing::error!("pty setup failed for {sid}: {e}");
        }
    }

    // Hidden tmux client attach argv — mirrors NavigateSession's attach flow.
    Ok(runtime::attach_args(&sid).await)
}

/// Everything needed to relaunch an existing session row under its own id.
pub struct RelaunchRequest {
    pub session:           Session,
    pub is_orchestrator:   bool,
    pub plan:              crate::restart::RefilePlan,
    /// The id to `--resume` (Resume) or a freshly minted one (fresh restart).
    pub claude_session_id: String,
    pub started_at:        i64,
    pub failure_status:    SessionStatus,
}

/// The shared relaunch sequence behind the app's Resume action and `ninox
/// fleet restore`: kill any stale pane, make sure the workspace exists,
/// then launch under the same session id.
pub async fn relaunch_in_place(
    engine:     Arc<Engine>,
    req:        RelaunchRequest,
    config:     &ninox_core::config::AppConfig,
    stream_pty: bool,
) -> Result<Vec<String>, String> {
    let id = req.session.id.clone();
    // A Resume/Re-file of a session still waiting in the restore queue
    // starts it now: take it out of line, keeping its held messages for
    // delivery below. (A no-op for a restore the queue itself launched.)
    let was_queued = engine.store.dequeue_waiting(&id).unwrap_or(false);
    let _ = ninox_core::runtime::kill_session(&id).await;
    if req.is_orchestrator {
        maybe_clear_dead_orchestrator_identity(&engine.store, &id).await;
    }
    // The worktree may have been torn down since the session ran (merge
    // cleanup, manual prune). Recreate it at the same path — claude-code
    // keys the conversation to that path, so this is what makes `--resume`
    // find it. On failure, fall through: `create_session` rejects a
    // missing workspace, so the spawn fails visibly into `failure_status`
    // instead of the agent silently starting in $HOME.
    if let Err(e) = ensure_session_workspace(&req.plan.workspace, &id, req.is_orchestrator, config, &req.session.agent_type).await {
        tracing::warn!("relaunch {id}: cannot restore workspace: {e}");
    }
    // Every resume, re-file, restart, fleet restore and queued relaunch
    // passes through here: re-seed so a recreated worktree, or a type whose
    // rules changed since the last launch, starts with the current profile.
    if let Err(e) = seed_permissions_for_type_name(
        std::path::Path::new(&req.plan.workspace), &req.session.agent_type, req.session.worker_type.as_deref(), config,
    ) {
        return Err(format!("{id}: {e:#}"));
    }
    let store = engine.store.clone();
    let launched = launch_interactive_session(
        engine,
        InteractiveSpawnParams {
            session_id:        id.clone(),
            name:              req.session.name,
            workspace:         req.plan.workspace,
            repo:              req.session.repo,
            orchestrator_id:   req.session.orchestrator_id,
            agent:             req.plan.agent,
            base_cmd:          req.plan.base_cmd,
            brain:             req.plan.brain,
            extra_env:         req.plan.extra_env,
            started_at:        req.started_at,
            claude_session_id: req.claude_session_id,
            failure_status:    req.failure_status,
            summary:           req.session.summary,
            permission_mode:   req.plan.permission_mode,
        },
        stream_pty,
    )
    .await;
    if was_queued && launched.is_ok() && store.held_message_count(&id).unwrap_or(0) > 0 {
        let mechanism = config.send_mechanism();
        tokio::spawn(async move {
            if !ninox_core::runtime::wait_for_input_prompt(&id, std::time::Duration::from_secs(90)).await {
                tracing::warn!("{id}: no input prompt; delivering held messages anyway");
            }
            if let Err(e) = ninox_core::messaging::deliver_held_messages(
                &store, &ninox_core::config::AppConfig::sessions_dir(), &id, mechanism,
            ).await {
                tracing::warn!("{id}: delivering held messages: {e}");
            }
        });
    }
    launched
}

/// Bounded wait, mirroring `tmux.rs::wait_for_input_prompt`'s poll-against-a-
/// deadline shape: confirming a process is dead is a kernel-level event
/// (`kill_session`'s signal plus the OS reaping it), not a slow user-facing
/// one like a harness drawing its prompt, so this polls far tighter than
/// `fleet.rs`'s `DEFAULT_PROMPT_TIMEOUT` (90s) — tune if real restart
/// teardown latency proves this too tight.
const DEAD_PID_POLL: Duration = Duration::from_millis(200);
const DEAD_PID_TIMEOUT: Duration = Duration::from_secs(3);

/// Orchestrator-only half of [`relaunch_in_place`]'s restart-identity fix
/// (see `docs/superpowers/specs/2026-10-22-orchestrator-identity-restart-design.md`):
/// if `orchestrator_id` has a persisted runtime identity whose root pid is
/// confirmed dead within a short bounded wait, clear it so the orchestrator's
/// next authorized action re-migrates a fresh identity from whichever pane
/// this relaunch actually starts. A no-op when there is no persisted row
/// (nothing to clear), and a deliberate no-op when the wait times out without
/// confirming death (fail-closed: the row stays stale rather than risk
/// clearing a still-valid identity racing against a slow `kill_session`).
async fn maybe_clear_dead_orchestrator_identity(store: &Store, orchestrator_id: &str) {
    let Ok(Some(persisted)) = store.orchestrator_runtime_identity(orchestrator_id) else {
        return;
    };
    let deadline = tokio::time::Instant::now() + DEAD_PID_TIMEOUT;
    loop {
        if !ninox_core::lifecycle::probe::is_pid_alive(persisted.root_pid) {
            match store.delete_dead_orchestrator_runtime(orchestrator_id, persisted.root_pid) {
                Ok(true) => tracing::info!(
                    "relaunch {orchestrator_id}: cleared stale runtime identity (old root pid {} confirmed dead)",
                    persisted.root_pid
                ),
                // Lost the TOCTOU race to a concurrent re-registration (or
                // already cleared by another relaunch) — nothing to do.
                Ok(false) => {}
                Err(e) => tracing::warn!("relaunch {orchestrator_id}: failed to clear stale identity: {e}"),
            }
            return;
        }
        if tokio::time::Instant::now() >= deadline {
            tracing::debug!(
                "relaunch {orchestrator_id}: old root pid {} still alive after {DEAD_PID_TIMEOUT:?}; leaving identity as-is",
                persisted.root_pid
            );
            return;
        }
        tokio::time::sleep(DEAD_PID_POLL).await;
    }
}

/// The tmux env for an app-spawned interactive session (Orchestrator or
/// Standalone): the shared NINOX_BIN/NINOX_CONFIG/NINOX_BRAIN vars, session
/// metadata attribution (`NINOX_SESSION`/`NINOX_DATA_DIR` — consumed by
/// the gh/git wrapper scripts in `ninox_core::hooks` and by the usage
/// poller's cost/token ingestion), plus any kind-specific extra vars.
///
/// Factored out from [`spawn_interactive_session`] for unit testing: this is
/// the fix for the gap where app-spawned sessions never set the session
/// attribution vars (only the CLI worker path in `main.rs::run_spawn` did),
/// making PR/branch metadata capture and cost attribution silently
/// invisible for orchestrators and standalone spawns.
pub(crate) fn interactive_env_vars<'a>(
    ninox_bin:      &'a str,
    ninox_config:   &'a str,
    brain_write:    &'a str,
    brain_reads:    &'a str,
    session_id:     &'a str,
    sessions_dir:   &'a str,
    extra_env:      &'a [(String, String)],
) -> Vec<(&'a str, &'a str)> {
    let mut env: Vec<(&str, &str)> = vec![
        ("NINOX_BIN",      ninox_bin),
        ("NINOX_CONFIG",   ninox_config),
        ("NINOX_BRAIN",    brain_write),
        ("NINOX_SESSION",  session_id),
        ("NINOX_DATA_DIR", sessions_dir),
        // Claude Code gates its cross-session messaging socket behind a
        // remote flag that defaults to OFF, and a session started without
        // it advertises no socket at all. Since that socket is what
        // `SendMechanism::SessionSocket` delivers over, leaving the gate to
        // chance means the configured mechanism silently degrades to
        // keystrokes on any machine the flag has not reached — working, but
        // never actually the mechanism that was chosen. This env var is the
        // gate's own first branch, so setting it makes the behaviour of a
        // ninox-spawned session deterministic instead of dependent on
        // someone else's rollout.
        (CLAUDE_MESSAGING_GATE_ENV, "1"),
    ];
    if !brain_reads.is_empty() {
        env.push((ninox_core::brain_set::READS_ENV, brain_reads));
    }
    for (k, v) in extra_env {
        env.push((k.as_str(), v.as_str()));
    }
    env
}

/// Expand a leading `~` or `~/` in a user-supplied path to the home directory.
/// Returns the input unchanged when it doesn't start with `~` (or when the
/// home directory can't be resolved).
pub fn expand_tilde(path: &str) -> String {
    if path == "~" {
        if let Some(home) = dirs::home_dir() {
            return home.to_string_lossy().to_string();
        }
    } else if let Some(rest) = path.strip_prefix("~/") {
        if let Some(home) = dirs::home_dir() {
            return home.join(rest).to_string_lossy().to_string();
        }
    }
    path.to_string()
}

/// Read `git remote get-url origin` from the workspace and parse it as a
/// GitHub slug (`owner/repo`). Returns `None` if git fails or the URL is not
/// a recognisable GitHub remote.
pub fn repo_from_workspace(workspace: &str) -> Option<String> {
    let output = std::process::Command::new("git")
        .args(["-C", workspace, "remote", "get-url", "origin"])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let url = String::from_utf8_lossy(&output.stdout).trim().to_string();
    ninox_core::github::split_repo(&url).map(|(o, r)| format!("{o}/{r}"))
}

/// Create an isolated git worktree for a session at
/// `{repo}/.claude/worktrees/{session_id}` on a new branch `{session_id}`.
///
/// Returns the worktree path on success. If the branch name already exists
/// (e.g. a previous run with the same name), the existing branch is checked
/// out rather than creating a new one.
///
/// Runs the (blocking) [`create_worktree_at`] core on a `spawn_blocking`
/// thread: this fn is always awaited from inside `Task::future` on the
/// app's shared tokio runtime, and `git worktree add` does a full working-
/// tree checkout, not the cheap metadata query `repo_from_workspace` does —
/// running it directly on the calling task would tie up a runtime worker
/// thread for that whole checkout.
///
/// `inbox_enabled` is whether the caller's configured send mechanism is
/// `SendMechanism::Inbox` (`AppConfig::send_mechanism()`), which is the only
/// one whose delivery depends on drain hooks existing in the worktree —
/// threaded through explicitly (rather than read here via `AppConfig::load()`)
/// so callers control it and tests can exercise both settings without
/// touching the real user config file. `config` is threaded through in full
/// (rather than a derived bool) so [`ensure_statusline_settings`] can gate
/// the identity hooks through the `whoami` capability's own registry entry —
/// see `ninox_core::identity::hooks_enabled` — instead of a hand-threaded
/// per-capability flag.
pub async fn create_worker_worktree(
    repo: &str, session_id: &str, inbox_enabled: bool, config: &ninox_core::config::AppConfig,
) -> anyhow::Result<String> {
    use anyhow::Context as _;

    let repo = repo.to_string();
    let session_id = session_id.to_string();
    let config = config.clone();
    tokio::task::spawn_blocking(ninox_core::test_isolation::propagate(move || {
        let worktree_path = std::path::Path::new(&repo)
            .join(".claude")
            .join("worktrees")
            .join(&session_id);
        create_worktree_at(
            std::path::Path::new(&repo), &worktree_path, &session_id,
            inbox_enabled, &config,
        )
    }))
    .await
    .context("worktree creation task panicked")?
}

/// Make sure a session's recorded `workspace_path` exists before a Resume
/// or Re-file respawn. Worker worktrees are torn down on completion
/// (`events::remove_worktree_and_artifacts`) and by users pruning
/// `.claude/worktrees/` — but claude-code keys its conversations to the cwd
/// *path string* (`~/.claude/projects/<escaped-path>/<uuid>.jsonl`, which
/// survives the teardown), so recreating the worktree at the exact same
/// path is what makes `--resume` find the conversation again. tmux itself
/// is no safety net: `new-session -c <missing-dir>` exits 0 and silently
/// starts the pane in $HOME (verified on tmux 3.6a), where `--resume` then
/// fails with "No conversation found with session ID".
///
/// - Path exists → nothing to do.
/// - Missing orchestrator workspace (`is_orchestrator`) → plain
///   `create_dir_all`, mirroring how the orchestrator spawn created it in
///   the first place — the conversation lookup only needs the path back.
/// - Missing and shaped like a ninox worktree (`{repo}/.claude/worktrees/
///   {session_id}`) → recreate it via [`create_worker_worktree`]. Cleanup
///   deletes the branch along with the worktree, and that's fine: a fresh
///   branch is cut from the repo's HEAD in that case (the conversation
///   lookup only needs the *path* back, not the branch), while a surviving
///   branch is checked out again. Re-seeds the worker skills the original
///   spawn wrote (git-excluded, so never on the branch either way) via
///   [`seed_worker_skills`], gated by `config` exactly as the spawn was.
/// - Missing and anything else → error, so the spawn fails visibly instead
///   of the agent silently running in the wrong directory.
pub async fn ensure_session_workspace(
    workspace:         &str,
    session_id:        &str,
    is_orchestrator:   bool,
    config:            &ninox_core::config::AppConfig,
    harness:           &str,
) -> anyhow::Result<()> {
    if std::path::Path::new(workspace).is_dir() {
        return Ok(());
    }
    if is_orchestrator {
        std::fs::create_dir_all(workspace)?;
        return Ok(());
    }
    let suffix = format!("/.claude/worktrees/{session_id}");
    let Some(repo_root) = workspace.strip_suffix(&suffix).filter(|r| !r.is_empty()) else {
        anyhow::bail!(
            "workspace {workspace} is gone and is not a ninox worker worktree — cannot recreate it"
        );
    };
    anyhow::ensure!(
        std::path::Path::new(repo_root).is_dir(),
        "workspace {workspace} is gone and its repo root {repo_root} no longer exists"
    );
    create_worker_worktree(
        repo_root, session_id, config.inbox_messaging.enabled, config,
    ).await?;
    seed_worker_skills(workspace, config, harness).await;
    Ok(())
}

/// Walk up from `start` (inclusive) looking for the nearest ancestor
/// directory containing a `.git` entry — either a real repo's `.git`
/// directory, or a linked worktree's `.git` gitfile. `start` itself need
/// not exist (or even have existing ancestors) since this only ever calls
/// `Path::exists`, which returns `false` rather than erroring for missing
/// paths — used by the Standalone spawn-modal's auto-create path, where
/// the user-typed workspace is by definition missing.
///
/// Returns `None` if no such ancestor is found before the filesystem root.
pub fn find_repo_root(start: &std::path::Path) -> Option<std::path::PathBuf> {
    let mut dir = Some(start);
    while let Some(d) = dir {
        if d.join(".git").exists() {
            return Some(d.to_path_buf());
        }
        dir = d.parent();
    }
    None
}

/// Core `git worktree add` logic shared by [`create_worker_worktree`]
/// (always nests under `{repo}/.claude/worktrees/{session_id}`) and the
/// Standalone spawn-modal's auto-create path (targets the exact user-typed
/// path via [`find_repo_root`]).
///
/// Returns the target path (stringified) on success. If `branch` already
/// exists (e.g. a previous run with the same name), the existing branch is
/// checked out rather than creating a new one. Blocking (not async): called
/// directly from the modal's synchronous confirm handler, which cannot
/// `.await`; mirrors the blocking `git` calls already used elsewhere in
/// this module (e.g. `repo_from_workspace`) even when invoked from async
/// call sites.
pub fn create_worktree_at(
    repo_root: &std::path::Path,
    target: &std::path::Path,
    branch: &str,
    inbox_enabled: bool,
    config: &ninox_core::config::AppConfig,
) -> anyhow::Result<String> {
    use anyhow::Context as _;
    use std::process::Command;

    let repo_str = repo_root.to_string_lossy().to_string();
    let target_str = target.to_string_lossy().to_string();

    // A worktree whose directory was deleted manually (`rm -rf`, not `git
    // worktree remove`) stays REGISTERED in git, and `git worktree add`
    // then refuses both the -b and existing-branch attempts below with
    // "missing but already registered worktree". Prune first — it only
    // clears registrations whose directories are already gone, so it can
    // never touch a live worktree. Best-effort: if it fails, the add
    // attempts below surface the real error.
    let _ = Command::new("git")
        .args(["-C", &repo_str, "worktree", "prune"])
        .output();

    // Attempt 1: create a fresh branch named after `branch`.
    let out = Command::new("git")
        .args(["-C", &repo_str, "worktree", "add", &target_str, "-b", branch])
        .output()
        .context("git worktree add")?;

    if out.status.success() {
        ensure_statusline_settings(target, inbox_enabled, config);
        write_ownership_marker(target, &repo_str, branch);
        return Ok(target_str);
    }

    // Attempt 2: branch already exists — check it out without -b.
    let stderr = String::from_utf8_lossy(&out.stderr);
    if stderr.contains("already exists") {
        let out2 = Command::new("git")
            .args(["-C", &repo_str, "worktree", "add", &target_str, branch])
            .output()
            .context("git worktree add (existing branch)")?;
        if out2.status.success() {
            ensure_statusline_settings(target, inbox_enabled, config);
            write_ownership_marker(target, &repo_str, branch);
            return Ok(target_str);
        }
        anyhow::bail!("{}", String::from_utf8_lossy(&out2.stderr).trim());
    }

    anyhow::bail!("{}", stderr.trim());
}

/// Resolves a human-typed Standalone-kind workspace path (tilde-expanded):
/// an existing directory is used as-is (no isolation — the GUI's and TUI's
/// Spawn dialogs let the human point at a path they already intend to work
/// in directly), and a not-yet-existing path nested under a git repo is
/// created as a fresh worktree there (so typing a brand-new path under an
/// existing checkout, e.g. `<repo>/.claude/worktrees/<branch>`, is a
/// request for that worktree rather than a rejection). A not-yet-existing
/// path with no enclosing repo is an error — spawning a session that could
/// never launch would just be a worse failure later.
pub fn resolve_standalone_workspace(
    input: &str, inbox_enabled: bool, config: &ninox_core::config::AppConfig,
) -> Result<String, String> {
    let workspace = expand_tilde(input);
    if std::path::Path::new(&workspace).exists() {
        return Ok(workspace);
    }
    let ws_path = std::path::Path::new(&workspace).to_path_buf();
    let repo_root = ws_path.parent().and_then(find_repo_root);
    match repo_root {
        Some(root) => {
            let branch = ws_path.file_name().and_then(|n| n.to_str()).unwrap_or(&workspace).to_string();
            create_worktree_at(&root, &ws_path, &branch, inbox_enabled, config)
                .map_err(|e| format!("failed to create worktree at {workspace}: {e}"))
        }
        None => Err(format!("workspace {workspace} does not exist")),
    }
}

/// Records the orphan sweeper's "ninox created this" signal in a freshly
/// created worktree — branch name equals session id by this module's own
/// convention. Best-effort: a marker write/exclude failure must never fail
/// the spawn itself.
fn write_ownership_marker(target: &std::path::Path, repo: &str, branch: &str) {
    let created_at = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_millis() as i64);
    let marker = ninox_core::workspace::WorkspaceMarker {
        session_id: branch.to_string(),
        repo: repo.to_string(),
        branch: branch.to_string(),
        created_at,
    };
    if let Err(e) = ninox_core::workspace::write_marker(target, &marker) {
        tracing::warn!("write ownership marker for {}: {e}", target.display());
        return;
    }
    if let Err(e) = git_exclude_add(target, ninox_core::workspace::MARKER_FILENAME) {
        tracing::warn!("exclude ownership marker for {}: {e}", target.display());
    }
}

/// Merge ninox's `statusLine`, the Stop/UserPromptSubmit/PreToolUse/
/// PermissionRequest activity hooks, and any `PreToolUse` guard a worker
/// capability installs into a freshly created worker worktree's
/// `.claude/settings.local.json` — the per-user, never-shared settings file,
/// since the commands carry a machine-specific binary path. The user's own
/// content there (and a checked-in `settings.json`) is left alone; ninox
/// entries an older build seeded into an untracked `settings.json` are
/// pruned (see `ninox_core::claude_settings`). Best-effort: any failure here
/// must never fail worktree creation itself, so errors are logged rather
/// than propagated.
///
/// The `Stop`/`UserPromptSubmit` hooks always carry the worker-status
/// activity commands (`ninox worker-status hook-stop`/`hook-prompt` — see
/// `ninox_core::worker_status`); `inbox_enabled` additionally prepends the
/// file-based inbox drains (`ninox inbox drain-stop`/`drain-prompt`, see
/// `ninox_core::inbox`). The harness invokes all of them with
/// `NINOX_SESSION`/`NINOX_DATA_DIR` already set (see
/// `interactive_env_vars`/`worker_env_vars`).
///
/// `PreToolUse` (matched on `AskUserQuestion|ExitPlanMode`) and
/// `PermissionRequest` (matched on
/// [`ninox_core::worker_status::PERMISSION_REQUEST_MATCHER`]) are also
/// always-on: they report a session waiting on a synchronous interactive
/// prompt mid-turn, the gap `UserPromptSubmit`/`Stop` alone can't see (the
/// turn hasn't ended while the agent is sitting at the prompt). See
/// `ninox worker-status hook-needs-input`/`hook-permission`.
///
/// `PreToolUse` entries come from `ninox_core::capabilities::hooks_for` —
/// the same registry `seed_worker_skills` reads for skill markdown, gated
/// the same way (today: `pr-watch-enforcement`, always-on). This is the
/// worker-side counterpart to `orchestrator_root::setup_orchestrator_root`'s
/// own hook seeding, and seeds the identical `ToolHook` value.
///
/// When the `whoami` capability's own registry gate is satisfied by
/// `config` (`[role_rehydration].enabled`), also appends a sibling
/// `identity-hook prompt` entry to `UserPromptSubmit` and installs a new
/// `SessionStart` event carrying `identity-hook session-start` — see
/// `ninox_core::identity::push_prompt_hook`/`set_session_start_hook`, shared
/// with `orchestrator_root::setup_orchestrator_root`'s identical wiring so
/// the two install sites can't drift apart.
fn ensure_statusline_settings(
    worktree_path: &std::path::Path, inbox_enabled: bool, config: &ninox_core::config::AppConfig,
) {
    use ninox_core::claude_settings::{self, LEGACY_SETTINGS, LOCAL_SETTINGS};

    let claude_dir = worktree_path.join(".claude");
    // The shared shim, never this process's own path: it is the one binary
    // every worker agrees on, and can't be clobbered by a stale build (see
    // `ninox_core::hooks::install_self_shim`).
    let ninox_bin = ninox_core::hooks::self_shim_path().display().to_string();
    // Single-quote the binary path (mirroring the PATH-prepend quoting above
    // in `spawn_interactive_session`): the default macOS config dir is
    // `~/Library/Application Support/...`, which contains a space, so an
    // unquoted path here would be split into two argv tokens by the shell
    // that ultimately runs this command and never resolve to the binary.
    let ninox_bin_quoted = format!("'{}'", ninox_bin.replace('\'', "'\\''"));
    let mut settings = serde_json::json!({
        ninox_core::harness::CROSS_SESSION_KEY: ninox_core::harness::CROSS_SESSION_ACCEPT,
        "statusLine": {
            "type": "command",
            "command": format!("{ninox_bin_quoted} statusline"),
            "refreshInterval": 20
        }
    });
    // Claude Code runs every entry in an event's `hooks` array, so the
    // opt-in inbox drains and the always-on worker-status activity hooks
    // compose as siblings here — `install_local` replaces any previous
    // ninox entries rather than appending a second copy.
    let hook = |cmd: &str| ninox_core::worker_status::hook_entry(&ninox_bin_quoted, cmd);
    let mut stop_hooks = Vec::new();
    let mut prompt_hooks = Vec::new();
    if inbox_enabled {
        stop_hooks.push(hook("inbox drain-stop"));
        prompt_hooks.push(hook("inbox drain-prompt"));
    }
    stop_hooks.push(hook("worker-status hook-stop"));
    prompt_hooks.push(hook("worker-status hook-prompt"));
    ninox_core::identity::push_prompt_hook(config, &ninox_bin_quoted, &mut prompt_hooks);
    let mut hooks = serde_json::json!({
        "Stop":             [{ "hooks": stop_hooks }],
        "UserPromptSubmit": [{ "hooks": prompt_hooks }],
        "PermissionRequest": [{
            "matcher": ninox_core::worker_status::PERMISSION_REQUEST_MATCHER,
            "hooks": [hook("worker-status hook-permission")]
        }]
    });
    ninox_core::identity::set_session_start_hook(config, &ninox_bin_quoted, &mut hooks);
    settings["hooks"] = hooks;

    if std::fs::create_dir_all(&claude_dir).is_err() {
        return;
    }

    // Hook-bearing capabilities (today: `pr-watch-enforcement`) write their
    // guard script alongside the always-on Stop/UserPromptSubmit hooks
    // above — same registry gate `seed_worker_skills` applies to skill
    // markdown, so a config-gated hook capability would be skipped here too.
    // Uses the threaded `config` parameter (not a fresh `AppConfig::load()`),
    // same as the identity hooks above, so a future hook capability with a
    // real gate stays testable without touching `~/.config/ninox/config.toml`.
    //
    // Always-on, same as the Stop/UserPromptSubmit activity hooks above —
    // not gated through the capability registry since this isn't an
    // agent-facing capability, just making the existing activity signal
    // correct for a case it currently misses entirely.
    let mut pre_tool_use = vec![serde_json::json!({
        "matcher": "AskUserQuestion|ExitPlanMode",
        "hooks": [hook("worker-status hook-needs-input")]
    })];
    for hook in ninox_core::capabilities::hooks_for(ninox_core::capabilities::Audience::Worker, config) {
        if std::fs::write(claude_dir.join(hook.script_name), hook.script).is_err() {
            continue;
        }
        let _ = git_exclude_add(worktree_path, &format!(".claude/{}", hook.script_name));
        pre_tool_use.push(serde_json::json!({
            "matcher": hook.matcher,
            "hooks": [{"type": "command", "command": format!("node .claude/{}", hook.script_name), "timeout": 5}]
        }));
    }
    settings["hooks"]["PreToolUse"] = serde_json::Value::Array(pre_tool_use);

    // A settings.json checked into the branch is the repo's, not ours to
    // rewrite (the edit would show up in the worker's diff) — only an
    // untracked one, i.e. seeded by an older ninox, is pruned. Hooks a
    // tracked one already runs aren't seeded again, or they'd fire twice.
    if git_tracked(worktree_path, &format!(".claude/{LEGACY_SETTINGS}")) {
        claude_settings::without_legacy_duplicates(&claude_dir, &mut settings);
    } else if let Err(e) = claude_settings::strip_legacy(&claude_dir) {
        tracing::warn!("worktree {}: {e:#}", worktree_path.display());
    }
    // `settings.local.json` is conventionally gitignored, but a repo whose
    // `.gitignore` doesn't cover it must still never see it as stageable.
    match claude_settings::install_local(&claude_dir, &settings) {
        Ok(()) => {
            let _ = git_exclude_add(worktree_path, &format!(".claude/{LOCAL_SETTINGS}"));
        }
        Err(e) => tracing::warn!("worktree {}: {e:#}", worktree_path.display()),
    }
}

/// Seed a permission-enforced worker type's allow/deny/ask rules into
/// `workspace`'s `.claude/settings.local.json` (git-excluded, like every
/// other ninox-seeded file there). Such a session launches without the
/// bypass flag (see `ninox_core::harness::permission_mode`), so without
/// these rules it would stop at a permission prompt on every tool call.
/// The lists are set exactly, so a rule removed from the type is revoked
/// on the next launch. Returns whether it wrote anything: a missing or
/// unenforced type leaves the workspace untouched.
pub fn seed_worker_type_permissions(
    workspace: &std::path::Path,
    worker_type: Option<&ninox_core::worker_type::WorkerTypeSpec>,
) -> anyhow::Result<bool> {
    use ninox_core::claude_settings::LOCAL_SETTINGS;
    let Some(spec) = worker_type.filter(|t| t.permissions.enabled) else {
        return Ok(false);
    };
    let rel = format!(".claude/{LOCAL_SETTINGS}");
    if git_tracked(workspace, &rel) {
        anyhow::bail!(
            "{rel} is tracked in {}; refusing to write worker type '{}' permission rules into a committed file",
            workspace.display(), spec.name,
        );
    }
    let rules = ninox_core::worker_type::seeded_permissions(&spec.permissions);
    ninox_core::claude_settings::set_permission_rules(&workspace.join(&rel), &rules)?;
    git_exclude_add(workspace, &rel)?;
    Ok(true)
}

/// [`seed_worker_type_permissions`] for the worker type named on a row or
/// launch skeleton, resolved against the current registry.
pub fn seed_permissions_for_type_name(
    workspace: &std::path::Path,
    harness: &str,
    worker_type: Option<&str>,
    config: &ninox_core::config::AppConfig,
) -> anyhow::Result<bool> {
    let types = config.worker_type_registry();
    let spec = worker_type.and_then(|t| types.get(t));
    config.registry().ensure_permissions_enforceable(harness, spec)?;
    seed_worker_type_permissions(workspace, spec)
}

/// Whether `rel_path` is tracked in `workspace`'s git index. Anything that
/// isn't provably tracked (including "not a git repo") is false.
fn git_tracked(workspace: &std::path::Path, rel_path: &str) -> bool {
    std::process::Command::new("git")
        .args(["-C", &workspace.to_string_lossy(), "ls-files", "--error-unmatch", "--", rel_path])
        .output()
        .is_ok_and(|o| o.status.success())
}

/// Idempotently append `rel_path` to the worktree's shared `.git/info/
/// exclude` — git's own per-checkout, local-only ignore mechanism. Unlike a
/// tracked `.gitignore`, this can never itself be committed and is enforced
/// regardless of what the target repo's own `.gitignore` does or doesn't
/// cover, so it's the one mechanism every seeded `.claude` path (settings,
/// skill markdown, hook scripts) is excluded through — see
/// [`ensure_statusline_settings`] and [`seed_worker_skill`].
///
/// Resolved via `git rev-parse --git-common-dir` from `workspace`, so a
/// linked worktree's entry lands in the one exclude file shared by the whole
/// repo/worktree set, not a per-worktree copy. Returns `Ok(())` without
/// writing anything if `workspace` isn't a git repo at all (nothing to
/// protect against a commit in that case).
///
/// Append-only (never a whole-file read-modify-write): even if two spawns
/// race on the same shared `info/exclude`, the worst case is a harmless
/// duplicate line, never a lost concurrent edit.
fn git_exclude_add(workspace: &std::path::Path, rel_path: &str) -> anyhow::Result<()> {
    use anyhow::Context as _;
    use std::io::Write as _;

    let out = std::process::Command::new("git")
        .args(["-C", &workspace.to_string_lossy(), "rev-parse", "--git-common-dir"])
        .output()
        .context("git rev-parse --git-common-dir")?;
    if !out.status.success() {
        return Ok(());
    }

    let common_dir_raw = String::from_utf8_lossy(&out.stdout).trim().to_string();
    let common_dir = if std::path::Path::new(&common_dir_raw).is_absolute() {
        std::path::PathBuf::from(&common_dir_raw)
    } else {
        workspace.join(&common_dir_raw)
    };
    let exclude_path = common_dir.join("info").join("exclude");

    let existing = std::fs::read_to_string(&exclude_path).unwrap_or_default();
    if existing.lines().any(|l| l.trim() == rel_path) {
        return Ok(());
    }

    if let Some(parent) = exclude_path.parent() {
        std::fs::create_dir_all(parent).context("create info dir")?;
    }
    let mut file = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&exclude_path)
        .context("open info/exclude for append")?;
    let mut buf = String::new();
    if !existing.is_empty() && !existing.ends_with('\n') {
        buf.push('\n');
    }
    buf.push_str(rel_path);
    buf.push('\n');
    file.write_all(buf.as_bytes()).context("append info/exclude")?;
    Ok(())
}

/// Writes `content` as `SKILL.md` under `.claude/skills/<name>/` inside
/// `workspace`, so a spawned worker/standalone session sees `<name>` as a
/// real Claude Code skill from the moment it starts, and makes sure the file
/// can never end up in a commit. Best-effort: any failure here should be
/// logged and swallowed by the caller, not treated as fatal to the spawn
/// (mirrors how `setup_orchestrator_root`'s own failures are handled in
/// `main.rs`).
///
/// Shared mechanism behind [`seed_worker_skills`]: (1) refuse to clobber a
/// copy that's already tracked in git, (2) write the file, (3) idempotently
/// exclude its path from the repo's shared `info/exclude` so it never shows
/// up as untracked/stageable.
async fn seed_worker_skill(workspace: &str, skills_rel: &str, name: &str, content: &str) -> anyhow::Result<()> {
    use anyhow::Context as _;
    use tokio::fs;

    let skill_dir = std::path::Path::new(workspace).join(skills_rel).join(name);
    let skill_path = skill_dir.join("SKILL.md");
    let repo_rel_path = format!("{skills_rel}/{name}/SKILL.md");

    // Guard against clobbering a copy that somehow already got committed
    // (e.g. a branch created before this exclude mechanism existed, or a
    // manual `git add -f`). Ignoring an already-tracked file is a no-op in
    // git — overwriting it here would silently rewrite committed content
    // that a later `git commit -am` would then happily pick up, exactly
    // what the exclude step below is meant to prevent.
    let tracked = tokio::process::Command::new("git")
        .args(["-C", workspace, "ls-files", "--error-unmatch", &repo_rel_path])
        .output()
        .await;
    if let Ok(out) = tracked {
        if out.status.success() {
            anyhow::bail!(
                "{name} skill file is already tracked in this repo — skipping write to avoid touching committed content"
            );
        }
    }

    fs::create_dir_all(&skill_dir).await.context("create skills/<name>")?;
    fs::write(&skill_path, content)
        .await
        .context("write SKILL.md")?;

    // `git_exclude_add` shells out and does blocking fs I/O — spawn_blocking
    // keeps this `async fn` from tying up a tokio worker thread for the
    // duration of the git subprocess, same reasoning as why
    // `create_worker_worktree` wraps the (also blocking) `create_worktree_at`.
    let workspace = workspace.to_string();
    let rel_path = format!("{skills_rel}/{name}/");
    tokio::task::spawn_blocking(move || git_exclude_add(std::path::Path::new(&workspace), &rel_path))
        .await
        .context("git_exclude_add task panicked")?
}

/// Seeds every worker-facing capability that `config` currently enables
/// into `workspace`, so a spawned worker/standalone session sees them as
/// real Claude Code skills from the moment it starts — durable, on-disk
/// instructions rather than one-shot lines in its initial prompt (which are
/// lost after context compaction).
///
/// The list, the markdown, and the per-capability gates all come from
/// `ninox_core::capabilities::REGISTRY`; `config` is read once here rather
/// than having each call site thread gating booleans down (today only the
/// worker `watch-pr` entry is gated, on `[pr_watch].enabled`).
///
/// Best-effort and infallible by design: an individual skill that can't be
/// written (e.g. a tracked copy already in the repo) is logged and skipped,
/// never fatal to the spawn — mirroring how `setup_orchestrator_root`'s own
/// failures are handled in `main.rs`.
///
/// `harness` selects extra skills directories beyond `.claude/skills` (pi
/// reads `.agents/skills`); every directory is written from the same
/// registry loop, so they cannot drift.
pub async fn seed_worker_skills(workspace: &str, config: &ninox_core::config::AppConfig, harness: &str) {
    use ninox_core::capabilities::{for_audience, Audience};

    let mut dirs = vec![".claude/skills".to_string()];
    dirs.extend(config.registry().spec(harness).extra_skills_dir);
    for cap in for_audience(Audience::Worker) {
        if !(cap.enabled)(config) {
            continue;
        }
        let Some(md) = cap.worker_md else { continue };
        for dir in &dirs {
            if let Err(e) = seed_worker_skill(workspace, dir, cap.name, md).await {
                tracing::warn!("failed to seed {} skill into {dir} in {workspace}: {e}", cap.name);
            }
        }
    }
}

