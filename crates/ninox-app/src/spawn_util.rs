pub async fn acquire_worker_checkout_at_for_incarnation(
    store: Arc<Store>,
    source_workspace: &str,
    target: &std::path::Path,
    session_id: &str,
    incarnation_id: &str,
    inbox_enabled: bool,
) -> anyhow::Result<WorkerCheckout> {
    use anyhow::Context as _;

    let source_workspace = source_workspace.to_string();
    let target = target.to_path_buf();
    let session_id = session_id.to_string();
    let incarnation_id = incarnation_id.to_string();
    tokio::task::spawn_blocking(move || {
        acquire_worker_checkout_at_for_incarnation_blocking(
            &store,
            &source_workspace,
            &target,
            &session_id,
            &incarnation_id,
            inbox_enabled,
        )
    })
    .await
    .context("explicit worker checkout allocation task panicked")?
}

pub fn acquire_worker_checkout_at_for_incarnation_blocking(
    store: &Store,
    source_workspace: &str,
    target: &std::path::Path,
    session_id: &str,
    incarnation_id: &str,
    inbox_enabled: bool,
) -> anyhow::Result<WorkerCheckout> {
    use anyhow::Context as _;

    let identity =
        ninox_core::worktree::RepositoryIdentity::resolve(std::path::Path::new(source_workspace))?;
    target
        .parent()
        .context("explicit worker checkout path has no parent")?;
    let branch = target
        .file_name()
        .and_then(|name| name.to_str())
        .context("explicit worker checkout path has no UTF-8 branch name")?;
    let lease = acquire_pooled_checkout(
        store,
        &identity,
        PoolAcquireRequest {
            session_id,
            incarnation_id,
            branch,
            target: PoolAcquireTarget::Explicit(target.to_path_buf()),
            inbox_enabled,
        },
    )?;
    Ok(WorkerCheckout {
        workspace: lease.path.to_string_lossy().to_string(),
        source_workspace: identity.top_level.to_string_lossy().to_string(),
        pooled_lease: Some(lease),
    })
}

struct PoolAcquireRequest<'a> {
    session_id: &'a str,
    incarnation_id: &'a str,
    branch: &'a str,
    target: PoolAcquireTarget,
    inbox_enabled: bool,
}

enum PoolAcquireTarget {
    Sibling,
    Managed(std::path::PathBuf),
    Explicit(std::path::PathBuf),
}

fn acquire_pooled_checkout(
    store: &Store,
    identity: &ninox_core::worktree::RepositoryIdentity,
    request: PoolAcquireRequest<'_>,
) -> anyhow::Result<PooledCheckoutLease> {
    let PoolAcquireRequest {
        session_id,
        incarnation_id,
        branch,
        target,
        inbox_enabled,
    } = request;
    for mut record in store.pooled_checkouts_by_common_git_dir(&identity.common_git_dir)? {
        if matches!(record.state, PooledCheckoutState::Provisioning) {
            let stale = match (
                record.session_id.as_deref(),
                record.owner_incarnation_id.as_deref(),
                record.lease_id.as_deref(),
            ) {
                (Some(session_id), Some(incarnation_id), Some(lease_id)) => {
                    let worker = store.current_worker_incarnation(session_id)?;
                    let session_terminal = store
                        .get_session(session_id)?
                        .is_some_and(|session| session.status.is_terminal());
                    let stale = worker.as_ref().is_none_or(|worker| {
                        worker.incarnation_id != incarnation_id
                            || matches!(
                                worker.state,
                                ninox_core::types::WorkerIncarnationState::Released
                            )
                    }) || session_terminal;
                    if stale {
                        let _ = store.quarantine_pooled_checkout_lease_for_incarnation(
                            &record.path,
                            session_id,
                            incarnation_id,
                            lease_id,
                            "recovering stale provisioning reservation",
                        );
                    }
                    stale
                }
                _ => false,
            };
            if stale {
                record = store
                    .pooled_checkout_by_path(&record.path)?
                    .context("stale provisioning record disappeared during recovery")?;
            }
        }
        if !matches!(record.state, PooledCheckoutState::Quarantined)
            || matches!(
                record.kind,
                ninox_core::types::PooledCheckoutKind::UnsafeLegacy
            )
        {
            continue;
        }
        if !record.path.exists() {
            let _ = store.remove_missing_quarantined_pooled_checkout(&record.path);
            continue;
        }
        let pooled = ninox_core::worktree::PooledWorktree::from_record(&record)
            .and_then(|pooled| {
                anyhow::ensure!(
                    pooled.matches_identity()?,
                    "quarantined checkout identity needs recovery"
                );
                Ok(pooled)
            })
            .or_else(|_| {
                ninox_core::worktree::PooledWorktree::recover_quarantined_creation(&record)
            });
        let Ok(pooled) = pooled else { continue };
        if pooled.detach_if_needed().is_ok() {
            let _ = store.recover_quarantined_pooled_checkout(
                &record.path,
                &pooled.worktree_git_dir,
                &pooled.worktree_identity,
            );
        }
    }

    {
        let claimed = if let PoolAcquireTarget::Explicit(path) = &target {
            match store.pooled_checkout_by_path(path)? {
                Some(record) => {
                    anyhow::ensure!(
                        record.common_git_dir == identity.common_git_dir,
                        "requested checkout path belongs to a different repository"
                    );
                    anyhow::ensure!(
                        matches!(record.state, PooledCheckoutState::Free),
                        "requested checkout path is unavailable: {}",
                        path.display()
                    );
                    store.claim_free_pooled_checkout_at_for_incarnation(
                        path,
                        &identity.common_git_dir,
                        session_id,
                        incarnation_id,
                        branch,
                    )?
                }
                None => None,
            }
        } else {
            let kind = match &target {
                PoolAcquireTarget::Sibling => ninox_core::types::PooledCheckoutKind::Sibling,
                PoolAcquireTarget::Managed(_) => ninox_core::types::PooledCheckoutKind::Managed,
                PoolAcquireTarget::Explicit(_) => {
                    anyhow::bail!("explicit checkout target reached automatic claim path")
                }
            };
            store.claim_lowest_free_pooled_checkout_of_kind_for_incarnation(
                &identity.common_git_dir,
                kind,
                session_id,
                incarnation_id,
                branch,
            )?
        };
        if let Some(lease) = claimed {
            match ninox_core::worktree::PooledWorktree::prepare_for_lease(&lease) {
                Ok(pooled) => {
                    let finalized = store.finalize_pooled_checkout_for_incarnation(
                        &lease.path,
                        session_id,
                        incarnation_id,
                        &lease.lease_id,
                        &pooled.worktree_git_dir,
                        &pooled.worktree_identity,
                    );
                    match finalized {
                        Ok(true) => {}
                        Ok(false) => anyhow::bail!(
                            "pooled checkout lease changed while preparing {}",
                            lease.path.display()
                        ),
                        Err(error) => {
                            let _ = store.quarantine_pooled_checkout_lease_for_incarnation(
                                &lease.path,
                                session_id,
                                incarnation_id,
                                &lease.lease_id,
                                &error.to_string(),
                            );
                            return Err(error);
                        }
                    }
                    ensure_statusline_settings(&lease.path, inbox_enabled);
                    return Ok(PooledCheckoutLease {
                        worktree_git_dir: Some(pooled.worktree_git_dir),
                        worktree_identity: Some(pooled.worktree_identity),
                        ..lease
                    });
                }
                Err(error) => {
                    let reason = error.to_string();
                    let _ = store.quarantine_pooled_checkout_lease_for_incarnation(
                        &lease.path,
                        session_id,
                        incarnation_id,
                        &lease.lease_id,
                        &reason,
                    );
                    tracing::warn!(
                        "quarantined pooled checkout {}: {reason}",
                        lease.path.display()
                    );
                    return Err(error);
                }
            }
        }

        let lease = match &target {
            PoolAcquireTarget::Explicit(path) => store.reserve_pooled_checkout_at_for_incarnation(
                &identity.top_level,
                &identity.common_git_dir,
                path,
                session_id,
                incarnation_id,
                branch,
            )?,
            PoolAcquireTarget::Managed(root) => store
                .reserve_managed_pooled_checkout_for_incarnation(
                    &identity.top_level,
                    &identity.common_git_dir,
                    root,
                    session_id,
                    incarnation_id,
                    branch,
                )?,
            PoolAcquireTarget::Sibling => store.reserve_pooled_checkout_for_incarnation(
                &identity.top_level,
                &identity.common_git_dir,
                session_id,
                incarnation_id,
                branch,
            )?,
        };
        match ninox_core::worktree::PooledWorktree::create(&lease) {
            Ok(pooled) => {
                let finalized = store.finalize_pooled_checkout_for_incarnation(
                    &lease.path,
                    session_id,
                    incarnation_id,
                    &lease.lease_id,
                    &pooled.worktree_git_dir,
                    &pooled.worktree_identity,
                );
                match finalized {
                    Ok(true) => {}
                    Ok(false) => anyhow::bail!(
                        "pooled checkout reservation changed while creating {}",
                        lease.path.display()
                    ),
                    Err(error) => {
                        let _ = store.quarantine_pooled_checkout_lease_for_incarnation(
                            &lease.path,
                            session_id,
                            incarnation_id,
                            &lease.lease_id,
                            &error.to_string(),
                        );
                        return Err(error);
                    }
                }
                ensure_statusline_settings(&lease.path, inbox_enabled);
                Ok(PooledCheckoutLease {
                    worktree_git_dir: Some(pooled.worktree_git_dir),
                    worktree_identity: Some(pooled.worktree_identity),
                    ..lease
                })
            }
            Err(error) => {
                if lease.path.exists() {
                    let _ = store.quarantine_pooled_checkout_lease_for_incarnation(
                        &lease.path,
                        session_id,
                        incarnation_id,
                        &lease.lease_id,
                        &error.to_string(),
                    );
                    tracing::warn!(
                        "quarantined unusable pooled checkout path {}: {error}",
                        lease.path.display()
                    );
                    return Err(error);
                }
                let _ = store.remove_failed_pooled_checkout_for_incarnation(
                    &lease.path,
                    session_id,
                    incarnation_id,
                    &lease.lease_id,
                );
                Err(error)
            }
        }
    }
}

pub async fn release_pooled_checkout_lease(
    store: Arc<Store>,
    lease: PooledCheckoutLease,
) -> anyhow::Result<bool> {
    tokio::task::spawn_blocking(move || {
        let pooled = ninox_core::worktree::PooledWorktree::from_lease(&lease)?;
        match pooled.release_clean() {
            Ok(_) => store.release_pooled_checkout_for_incarnation(
                &lease.path,
                &lease.session_id,
                &lease.owner_incarnation_id,
                &lease.lease_id,
            ),
            Err(error) => {
                let reason = error.to_string();
                let quarantined = store.quarantine_pooled_checkout_lease_for_incarnation(
                    &lease.path,
                    &lease.session_id,
                    &lease.owner_incarnation_id,
                    &lease.lease_id,
                    &reason,
                )?;
                if quarantined {
                    tracing::warn!(
                        "quarantined pooled checkout {}: {reason}",
                        lease.path.display()
                    );
                }
                Ok(quarantined)
            }
        }
    })
    .await
    .map_err(|error| anyhow::anyhow!("pooled checkout release task panicked: {error}"))?
}

pub async fn rollback_managed_worktree(
    workspace: &str,
    session_id: &str,
) -> anyhow::Result<bool> {
    let Some(metadata) = ninox_core::worktree::ManagedWorktree::load_for_workspace(
        std::path::Path::new(workspace),
        session_id,
    )? else {
        return Ok(false);
    };
    tokio::task::spawn_blocking(move || metadata.remove_checkout_if_matches())
        .await
        .map_err(|error| anyhow::anyhow!("managed worktree rollback task panicked: {error}"))?
}

pub async fn rollback_worker_checkout(
    store: Arc<Store>,
    checkout: &WorkerCheckout,
    session_id: &str,
) -> anyhow::Result<bool> {
    if let Some(lease) = checkout.pooled_lease.clone() {
        return release_pooled_checkout_lease(store, lease).await;
    }
    rollback_managed_worktree(&checkout.workspace, session_id).await
}

pub fn release_unbound_worker_incarnation_blocking(
    store: &Store,
    session_id: &str,
    incarnation_id: &str,
) -> bool {
    let Ok(Some(claim)) = store.claim_worker_cleanup(session_id, incarnation_id) else {
        return false;
    };
    store
        .complete_worker_claim(
            session_id,
            &claim.incarnation_id,
            ninox_core::types::WorkerIncarnationState::CleanupClaimed,
        )
        .unwrap_or(false)
}

pub async fn rollback_worker_incarnation_checkout(
    store: Arc<Store>,
    session_id: &str,
    incarnation_id: &str,
    checkout: Option<&WorkerCheckout>,
) -> bool {
    let claim = checkout
        .and_then(|checkout| checkout.pooled_lease.as_ref())
        .map_or_else(
            || store.claim_worker_cleanup(session_id, incarnation_id),
            |lease| {
                store.claim_worker_cleanup_with_lease(
                    session_id,
                    incarnation_id,
                    &lease.lease_id,
                )
            },
        );
    let Ok(Some(claim)) = claim else {
        return false;
    };
    if let Some(checkout) = checkout {
        let _ = rollback_worker_checkout(store.clone(), checkout, session_id).await;
    }
    store
        .complete_worker_claim(
            session_id,
            &claim.incarnation_id,
            ninox_core::types::WorkerIncarnationState::CleanupClaimed,
        )
        .unwrap_or(false)
}

pub async fn stop_exact_worker_runtime(
    session_id: &str,
    incarnation_id: &str,
    caller_session: Option<&str>,
) -> anyhow::Result<()> {
    let runtime = ninox_core::tmux::session_env(session_id, "NINOX_WORKER_INCARNATION").await?;
    let Some(runtime) = runtime else {
        return Ok(());
    };
    anyhow::ensure!(
        runtime == incarnation_id,
        "worker runtime changed; refusing to stop a successor"
    );
    anyhow::ensure!(
        caller_session != Some(session_id),
        "worker {session_id} cannot release its checkout while its own runtime is active"
    );
    ninox_core::tmux::kill_session(session_id).await?;
    anyhow::ensure!(
        ninox_core::tmux::session_env(session_id, "NINOX_WORKER_INCARNATION")
            .await?
            .is_none(),
        "worker runtime absence could not be confirmed after stop"
    );
    Ok(())
}

/// Create an isolated git worktree for a session at
/// `{repo}/.claude/worktrees/{session_id}` on a new branch `{session_id}`.
///
/// Returns the worktree path on success. If the branch name already exists
/// (e.g. a previous run with the same name), the existing branch is checked
/// out rather than creating a new one.
///
/// Runs the (blocking) [`create_worktree_at`] core on a `spawn_blocking`
/// thread: this fn is always awaited from inside `Task::future` on the
/// app's shared tokio runtime, and `git worktree add` does a full working-
/// tree checkout, not the cheap metadata query `repo_from_workspace` does —
/// running it directly on the calling task would tie up a runtime worker
/// thread for that whole checkout.
///
/// `inbox_enabled` is the caller's `AppConfig.inbox_messaging.enabled` —
/// threaded through explicitly (rather than read here via
/// `AppConfig::load()`) so callers control it and tests can exercise both
/// states without touching the real user config file. See
/// `ensure_statusline_settings`.
#[cfg(test)]
pub async fn create_worker_worktree(
    repo: &str, session_id: &str, inbox_enabled: bool,
) -> anyhow::Result<String> {
    use anyhow::Context as _;

    let repo = repo.to_string();
    let session_id = session_id.to_string();
    tokio::task::spawn_blocking(move || {
        let worktree_path = std::path::Path::new(&repo)
            .join(".claude")
            .join("worktrees")
            .join(&session_id);
        create_worktree_at(std::path::Path::new(&repo), &worktree_path, &session_id, inbox_enabled)
    })
    .await
    .context("worktree creation task panicked")?
}

/// Make sure a session's recorded `workspace_path` exists before a Resume
/// or Re-file respawn. Worker worktrees are torn down on completion
/// (`events::remove_worktree_and_artifacts`) and by users pruning
/// `.claude/worktrees/` — but claude-code keys its conversations to the cwd
/// *path string* (`~/.claude/projects/<escaped-path>/<uuid>.jsonl`, which
/// survives the teardown), so recreating the worktree at the exact same
/// path is what makes `--resume` find the conversation again. tmux itself
/// is no safety net: `new-session -c <missing-dir>` exits 0 and silently
/// starts the pane in $HOME (verified on tmux 3.6a), where `--resume` then
/// fails with "No conversation found with session ID".
///
/// - Path exists → nothing to do.
/// - Missing orchestrator workspace (`is_orchestrator`) → plain
///   `create_dir_all`, mirroring how the orchestrator spawn created it in
///   the first place — the conversation lookup only needs the path back.
/// - Missing and shaped like a ninox worktree (`{repo}/.claude/worktrees/
///   {session_id}`) → recreate it via [`create_worker_worktree`]. Cleanup
///   deletes the branch along with the worktree, and that's fine: a fresh
///   branch is cut from the repo's HEAD in that case (the conversation
///   lookup only needs the *path* back, not the branch), while a surviving
///   branch is checked out again. Re-seeds the brain skill the original
///   spawn wrote (git-excluded, so never on the branch either way).
/// - Missing and anything else → error, so the spawn fails visibly instead
///   of the agent silently running in the wrong directory.
pub async fn ensure_session_workspace(
    workspace:       &str,
    session_id:      &str,
    is_orchestrator: bool,
    inbox_enabled:   bool,
) -> anyhow::Result<()> {
    if is_orchestrator {
        std::fs::create_dir_all(workspace)?;
        return Ok(());
    }
    if std::path::Path::new(workspace).is_dir() {
        ensure_statusline_settings(std::path::Path::new(workspace), inbox_enabled);
        if let Err(e) = seed_worker_brain_skill(workspace).await {
            tracing::warn!("failed to re-seed brain skill for {session_id}: {e}");
        }
        return Ok(());
    }
    if let Some(mut managed) = ninox_core::worktree::ManagedWorktree::load_for_workspace(
        std::path::Path::new(workspace),
        session_id,
    )? {
        managed.add_checkout()?;
        ensure_statusline_settings(&managed.worktree_path, inbox_enabled);
        if let Err(error) = managed.persist() {
            let _ = managed.remove_checkout_if_matches_with_metadata(false);
            return Err(error);
        }
        if let Err(e) = seed_worker_brain_skill(workspace).await {
            tracing::warn!("failed to re-seed brain skill for {session_id}: {e}");
        }
        return Ok(());
    }
    let suffix = format!("/.claude/worktrees/{session_id}");
    let Some(repo_root) = workspace.strip_suffix(&suffix).filter(|r| !r.is_empty()) else {
        anyhow::bail!(
            "workspace {workspace} is gone and is not a ninox worker worktree — cannot recreate it"
        );
    };
    anyhow::ensure!(
        std::path::Path::new(repo_root).is_dir(),
        "workspace {workspace} is gone and its repo root {repo_root} no longer exists"
    );
    create_worktree_at(
        std::path::Path::new(repo_root),
        std::path::Path::new(workspace),
        session_id,
        inbox_enabled,
    )?;
    if let Err(e) = seed_worker_brain_skill(workspace).await {
        tracing::warn!("failed to re-seed brain skill for {session_id}: {e}");
    }
    Ok(())
}

pub async fn ensure_session_workspace_with_store(
    store: &Store,
    workspace: &str,
    session_id: &str,
    is_orchestrator: bool,
    inbox_enabled: bool,
) -> anyhow::Result<()> {
    if !is_orchestrator {
        if let Some(mut record) = store.pooled_checkout_by_session(session_id)? {
            if matches!(record.state, PooledCheckoutState::Provisioning) {
                let lease_id = record
                    .lease_id
                    .clone()
                    .ok_or_else(|| anyhow::anyhow!("provisioning checkout has no lease id"))?;
                if !record.path.exists() {
                    let _ = store.remove_failed_pooled_checkout(
                        &record.path,
                        session_id,
                        &lease_id,
                    );
                    anyhow::bail!(
                        "crash-interrupted pooled checkout {} was not created; re-file again to allocate a replacement",
                        record.path.display()
                    );
                }
                let recovered =
                    ninox_core::worktree::PooledWorktree::recover_provisioning(&record)?;
                anyhow::ensure!(
                    store.finalize_pooled_checkout(
                        &record.path,
                        session_id,
                        &lease_id,
                        &recovered.worktree_git_dir,
                        &recovered.worktree_identity,
                    )?,
                    "pooled checkout lease changed during crash recovery"
                );
                record = store
                    .pooled_checkout_by_session(session_id)?
                    .ok_or_else(|| anyhow::anyhow!("recovered pooled checkout disappeared"))?;
            }
            anyhow::ensure!(
                record.path == std::path::Path::new(workspace),
                "session {session_id} owns pooled checkout {}, not {workspace}",
                record.path.display()
            );
            anyhow::ensure!(
                matches!(record.state, PooledCheckoutState::Leased),
                "pooled checkout {} is not ready",
                record.path.display()
            );
            let pooled = ninox_core::worktree::PooledWorktree::from_record(&record)?;
            anyhow::ensure!(
                pooled.matches_identity()?,
                "pooled checkout {} no longer matches its Ninox identity",
                record.path.display()
            );
            ensure_statusline_settings(&record.path, inbox_enabled);
            if let Err(e) = seed_worker_brain_skill(workspace).await {
                tracing::warn!("failed to re-seed brain skill for {session_id}: {e}");
            }
            return Ok(());
        }
        if let Some(record) =
            store.pooled_checkout_by_path(std::path::Path::new(workspace))?
        {
            anyhow::bail!(
                "pooled checkout {} is {:?} and is no longer leased to session {session_id}",
                record.path.display(),
                record.state
            );
        }
    }
    ensure_session_workspace(workspace, session_id, is_orchestrator, inbox_enabled).await
}

/// Walk up from `start` (inclusive) looking for the nearest ancestor
/// directory containing a `.git` entry — either a real repo's `.git`
/// directory, or a linked worktree's `.git` gitfile. `start` itself need
/// not exist (or even have existing ancestors) since this only ever calls
/// `Path::exists`, which returns `false` rather than erroring for missing
/// paths — used by the Standalone spawn-modal's auto-create path, where
/// the user-typed workspace is by definition missing.
///
/// Returns `None` if no such ancestor is found before the filesystem root.
pub fn find_repo_root(start: &std::path::Path) -> Option<std::path::PathBuf> {
    let mut dir = Some(start);
    while let Some(d) = dir {
        if d.join(".git").exists() {
            return Some(d.to_path_buf());
        }
        dir = d.parent();
    }
    None
}

/// Core `git worktree add` logic shared by [`create_worker_worktree`]
/// (always nests under `{repo}/.claude/worktrees/{session_id}`) and the
/// Standalone spawn-modal's auto-create path (targets the exact user-typed
/// path via [`find_repo_root`]).
///
/// Returns the target path (stringified) on success. If `branch` already
/// exists (e.g. a previous run with the same name), the existing branch is
/// checked out rather than creating a new one. Blocking (not async): called
/// directly from the modal's synchronous confirm handler, which cannot
/// `.await`; mirrors the blocking `git` calls already used elsewhere in
/// this module (e.g. `repo_from_workspace`) even when invoked from async
/// call sites.
pub fn create_worktree_at(
    repo_root: &std::path::Path,
    target: &std::path::Path,
    branch: &str,
    inbox_enabled: bool,
) -> anyhow::Result<String> {
    use anyhow::Context as _;
    use std::process::Command;

    let repo_str = repo_root.to_string_lossy().to_string();
    let target_str = target.to_string_lossy().to_string();

    // A worktree whose directory was deleted manually (`rm -rf`, not `git
    // worktree remove`) stays REGISTERED in git, and `git worktree add`
    // then refuses both the -b and existing-branch attempts below with
    // "missing but already registered worktree". Prune first — it only
    // clears registrations whose directories are already gone, so it can
    // never touch a live worktree. Best-effort: if it fails, the add
    // attempts below surface the real error.
    let _ = Command::new("git")
        .args(["-C", &repo_str, "worktree", "prune"])
        .output();

    // Attempt 1: create a fresh branch named after `branch`.
    let out = Command::new("git")
        .args(["-C", &repo_str, "worktree", "add", &target_str, "-b", branch])
        .output()
        .context("git worktree add")?;

    if out.status.success() {
        ensure_statusline_settings(target, inbox_enabled);
        return Ok(target_str);
    }

    // Attempt 2: branch already exists — check it out without -b.
    let stderr = String::from_utf8_lossy(&out.stderr);
    if stderr.contains("already exists") {
        let out2 = Command::new("git")
            .args(["-C", &repo_str, "worktree", "add", &target_str, branch])
            .output()
            .context("git worktree add (existing branch)")?;
        if out2.status.success() {
            ensure_statusline_settings(target, inbox_enabled);
            return Ok(target_str);
        }
        anyhow::bail!("{}", String::from_utf8_lossy(&out2.stderr).trim());
    }

    anyhow::bail!("{}", stderr.trim());
}

/// Write a minimal `.claude/settings.json` (`statusLine`, plus the inbox
/// drain hooks when opt-in messaging is enabled) into a freshly created
/// worker worktree, unless one already exists (e.g. checked into the
/// branch). Best-effort: any failure here must never fail worktree
/// creation itself, so errors are swallowed rather than propagated.
///
/// `inbox_enabled` gates the `Stop`/`UserPromptSubmit` hooks that drain the
/// file-based inbox (`ninox_core::inbox`) — off (the default), this
/// produces byte-for-byte the same settings as before that feature existed.
/// On, it installs hooks that run `ninox inbox drain-stop`/`drain-prompt`,
/// which the harness invokes with `NINOX_SESSION`/`NINOX_DATA_DIR` already
/// set (see `interactive_env_vars`/`worker_env_vars`).
fn ensure_statusline_settings(worktree_path: &std::path::Path, inbox_enabled: bool) {
    let claude_dir = worktree_path.join(".claude");
    let settings_path = claude_dir.join("settings.json");
    if git_path_is_tracked(worktree_path, ".claude/settings.json") {
        return;
    }
    if settings_path.exists()
        && !std::fs::read_to_string(&settings_path)
            .ok()
            .and_then(|body| serde_json::from_str::<serde_json::Value>(&body).ok())
            .and_then(|settings| {
                settings
                    .get("ninoxManaged")
                    .and_then(serde_json::Value::as_bool)
            })
            .unwrap_or(false)
    {
        return;
    }
    let ninox_bin = ninox_core::config::AppConfig::ninox_bin_dir().join("ninox").display().to_string();
    // Single-quote the binary path (mirroring the PATH-prepend quoting above
    // in `spawn_interactive_session`): the default macOS config dir is
    // `~/Library/Application Support/...`, which contains a space, so an
    // unquoted path here would be split into two argv tokens by the shell
    // that ultimately runs this command and never resolve to the binary.
    let ninox_bin_quoted = format!("'{}'", ninox_bin.replace('\'', "'\\''"));
    let mut settings = serde_json::json!({
        "ninoxManaged": true,
        "statusLine": {
            "type": "command",
            "command": format!("{ninox_bin_quoted} statusline"),
            "refreshInterval": 20
        }
    });
    if inbox_enabled {
        // Claude Code hook `timeout` is in SECONDS, not milliseconds — 5
        // gives these fast, local-filesystem-only drains a generous margin
        // without risking an accidental multi-minute hang on a hook error.
        settings["hooks"] = serde_json::json!({
            "Stop": [{
                "hooks": [{
                    "type": "command",
                    "command": format!("{ninox_bin_quoted} inbox drain-stop"),
                    "timeout": 5
                }]
            }],
            "UserPromptSubmit": [{
                "hooks": [{
                    "type": "command",
                    "command": format!("{ninox_bin_quoted} inbox drain-prompt"),
                    "timeout": 5
                }]
            }]
        });
    }
    if std::fs::create_dir_all(&claude_dir).is_ok() {
        if let Ok(body) = serde_json::to_string_pretty(&settings) {
            if std::fs::write(&settings_path, body).is_ok() {
                exclude_generated_provider_file(worktree_path, ".claude/settings.json");
            }
        }
    }
}

