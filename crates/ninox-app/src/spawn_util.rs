//! Shared spawn plumbing used by both the CLI worker path (`main.rs
//! run_spawn`) and the in-app standalone spawn (`app.rs SpawnFormConfirm`):
//! isolated worktree creation, repo-slug detection, tilde expansion, and the
//! interactive tmux+PTY launch sequence shared by both spawn-modal kinds.

use std::sync::Arc;

use anyhow::Context as _;
use ninox_core::{
    events::Engine, pty, tmux, Event, PooledCheckoutLease, PooledCheckoutState, Session,
    SessionFields, SessionStatus, Store,
};

/// The per-kind differences between the spawn-modal launch paths
/// (standalone vs orchestrator). Everything else — env resolution,
/// PATH-prepend launch command, tmux session creation, pid lookup,
/// session persistence, and PTY streaming — is identical and lives in
/// [`spawn_interactive_session`].
pub struct InteractiveSpawnParams {
    /// Session id; also used as the tmux session name.
    pub session_id:      String,
    pub name:            String,
    /// Directory the agent starts in (isolated worktree for standalone,
    /// per-orchestrator subdirectory for orchestrators). Recorded as the
    /// session's `workspace_path`.
    pub workspace:       String,
    /// GitHub `owner/repo` slug ("" when unknown / not applicable).
    pub repo:            String,
    pub orchestrator_id: Option<String>,
    pub agent:           ninox_core::config::AgentConfig,
    /// Resolved interactive launch command (registry-resolved by the
    /// caller: `AppConfig::registry().interactive_cmd(&agent)`). Kept
    /// separate from `agent` so this module needs no registry access;
    /// `agent` remains for session-record stamping (agent_type/model).
    pub base_cmd:        String,
    /// Brain catalogue path, exported as `NINOX_BRAIN` for both kinds.
    pub catalogue_path:  String,
    /// Extra env pairs beyond the shared NINOX_BIN/NINOX_CONFIG/NINOX_BRAIN
    /// (e.g. NINOX_ORCHESTRATOR_ID + caller-type vars for orchestrators).
    pub extra_env:       Vec<(String, String)>,
    pub started_at:      i64,
    /// UUID for `--session-id`/`--resume` (see `ninox_core::harness::new_claude_session_id`).
    /// Generated by the caller — this module never generates one itself,
    /// so `Re-file` (Task 8) can mint a fresh id while Resume (Task 10)
    /// reuses the session's existing one.
    pub claude_session_id: String,
    /// Status to set if `tmux::create_session` fails. `Terminated` for a
    /// fresh spawn or Re-file (nothing worth preserving); `Interrupted`
    /// for Resume (keep it retryable — see the design spec's Error
    /// Handling section).
    pub failure_status:  ninox_core::SessionStatus,
    /// One-line task summary carried over from the session being
    /// respawned (Re-file/Resume); `None` for a fresh spawn, which has no
    /// prior summary to preserve.
    pub summary:         Option<String>,
}

/// Launch an interactive agent session inside tmux and start PTY streaming.
///
/// On success, returns the tmux attach argv for the new session so the
/// caller can emit `Message::ClientAttach` and render it immediately at the
/// right size (the attached-client flow sizes the PTY to the real panel).
/// On tmux failure (e.g. the workspace path is bad) the session is marked
/// with the caller-supplied `p.failure_status` in the store (`Terminated`
/// for a fresh spawn or Re-file, `Interrupted` for Resume — see
/// `InteractiveSpawnParams::failure_status`), a `SessionUpdated` event is
/// emitted so the UI reflects the new status instead of a session stuck in
/// Working forever, and `None` is returned.
pub async fn spawn_interactive_session(
    engine: Arc<Engine>,
    p: InteractiveSpawnParams,
) -> Option<Vec<String>> {
    let sid = p.session_id;
    let is_orchestrator = p
        .extra_env
        .iter()
        .any(|(key, value)| key == "NINOX_CALLER_TYPE" && value == "orchestrator");

    let ninox_bin = std::env::current_exe()
        .ok()
        .and_then(|x| x.to_str().map(str::to_string))
        .unwrap_or_else(|| "ninox".to_string());
    let ninox_config = ninox_core::config::AppConfig::config_path()
        .to_string_lossy()
        .to_string();
    // Session metadata dir — must be set for both Orchestrator and Standalone
    // kinds, mirroring the CLI worker path (`main.rs run_spawn`). Without
    // these, the gh/git wrapper scripts (`ninox_core::hooks`) have nowhere to
    // record PR/branch metadata for app-spawned sessions, and the usage
    // poller has no session id to attribute cost/token ingestion to.
    let sessions_dir = ninox_core::config::AppConfig::sessions_dir();
    std::fs::create_dir_all(&sessions_dir).ok();
    let sessions_dir_str = sessions_dir.to_string_lossy().to_string();

    let env = interactive_env_vars(
        &ninox_bin, &ninox_config, &p.catalogue_path, &sid, &sessions_dir_str, &p.extra_env,
    );

    // Prepend ninox bin dir inside the shell command so the `ninox` shim
    // (which points to the current binary) is found first — even after
    // login-shell rc files reorder PATH.
    let ninox_bin_dir = ninox_core::config::AppConfig::ninox_bin_dir();
    let ninox_bin_dir_str = ninox_bin_dir.display().to_string().replace('\'', "'\\''");
    let base_cmd = p.base_cmd;
    let launch_cmd = format!("export PATH='{ninox_bin_dir_str}':\"$PATH\"; {base_cmd}");

    if let Err(e) = tmux::create_session(&sid, &p.workspace, &launch_cmd, &env).await {
        tracing::error!("tmux create failed for {sid}: {e}");
        // Surface the failure: without this the optimistically inserted
        // session would sit in Working forever.
        if engine
            .store
            .update_session_status_snapshot(&sid, p.started_at, p.failure_status)
            .unwrap_or(false)
        {
            if let Ok(Some(s)) = engine.store.get_session(&sid) {
                engine.emit(Event::SessionUpdated(s, SessionFields::STATUS));
            }
        }
        return None;
    }
    if is_orchestrator {
        if let Err(error) =
            ninox_core::workers::register_live_orchestrator_runtime(&engine.store, &sid).await
        {
            tracing::error!("orchestrator runtime registration failed for {sid}: {error}");
            let _ = tmux::kill_private_session(&sid).await;
            let _ = engine
                .store
                .update_session_status_snapshot(&sid, p.started_at, p.failure_status);
            return None;
        }
    }

    tokio::time::sleep(tokio::time::Duration::from_millis(300)).await;

    let pid = tmux::list_sessions()
        .await
        .ok()
        .and_then(|ss| ss.into_iter().find(|s| s.id == sid))
        .and_then(|s| s.pid);

    // Resume and Re-file respawn an *existing* row — carry forward every
    // field the spawn isn't authoritative for (PR linkage, gate breakdown,
    // accumulated cost, context readout) instead of hardcoding it empty,
    // which wiped all of them from both the store and (via the ALL-flagged
    // emit below) app memory until the pollers re-derived them. A fresh
    // spawn's optimistically-inserted row holds exactly these empty values
    // anyway, so carrying them forward is a no-op there. Read the row here
    // — after the awaits above, with none between read and write — so the
    // ALL emit's payload is fresh by construction. `terminal_at` is NOT
    // carried: the session is back to Working, so the retention countdown
    // ends.
    let prior = engine.store.get_session(&sid).ok().flatten();
    let prior = prior.as_ref();
    let updated = Session {
        id:              sid.clone(),
        orchestrator_id: p.orchestrator_id,
        name:            p.name,
        repo:            p.repo,
        status:          SessionStatus::Working,
        agent_type:      p.agent.harness.clone(),
        cost_usd:        prior.map_or(0.0, |s| s.cost_usd),
        started_at:      p.started_at,
        pr_number:       prior.and_then(|s| s.pr_number),
        pr_id:           prior.and_then(|s| s.pr_id),
        workspace_path:  Some(p.workspace),
        pid,
        model:           p.agent.model.clone(),
        context_tokens:  prior.and_then(|s| s.context_tokens),
        catalogue_path:  (!p.catalogue_path.is_empty()).then(|| p.catalogue_path.clone()),
        context_used_pct:     prior.and_then(|s| s.context_used_pct),
        context_total_tokens: prior.and_then(|s| s.context_total_tokens),
        context_window_size:  prior.and_then(|s| s.context_window_size),
        claude_session_id: Some(p.claude_session_id),
        summary:         p.summary,
        terminal_at:     None,
        gate_status:     prior.and_then(|s| s.gate_status.clone()),
    };
    let _ = engine.store.upsert_session(&updated);
    engine.emit(Event::SessionUpdated(updated, SessionFields::ALL));

    if let Err(e) = pty::start_streaming(engine.clone(), sid.clone(), &sid).await {
        tracing::error!("pty setup failed for {sid}: {e}");
    }

    // Hidden tmux client attach argv — mirrors NavigateSession's attach flow.
    Some(tmux::attach_args(&sid).await)
}

/// The tmux env for an app-spawned interactive session (Orchestrator or
/// Standalone): the shared NINOX_BIN/NINOX_CONFIG/NINOX_BRAIN vars, session
/// metadata attribution (`NINOX_SESSION`/`NINOX_DATA_DIR` — consumed by
/// the gh/git wrapper scripts in `ninox_core::hooks` and by the usage
/// poller's cost/token ingestion), plus any kind-specific extra vars.
///
/// Factored out from [`spawn_interactive_session`] for unit testing: this is
/// the fix for the gap where app-spawned sessions never set the session
/// attribution vars (only the CLI worker path in `main.rs::run_spawn` did),
/// making PR/branch metadata capture and cost attribution silently
/// invisible for orchestrators and standalone spawns.
fn interactive_env_vars<'a>(
    ninox_bin:      &'a str,
    ninox_config:   &'a str,
    catalogue_path: &'a str,
    session_id:     &'a str,
    sessions_dir:   &'a str,
    extra_env:      &'a [(String, String)],
) -> Vec<(&'a str, &'a str)> {
    let mut env: Vec<(&str, &str)> = vec![
        ("NINOX_BIN",      ninox_bin),
        ("NINOX_CONFIG",   ninox_config),
        ("NINOX_BRAIN",    catalogue_path),
        ("NINOX_SESSION",  session_id),
        ("NINOX_DATA_DIR", sessions_dir),
    ];
    for (k, v) in extra_env {
        env.push((k.as_str(), v.as_str()));
    }
    env
}

/// Expand a leading `~` or `~/` in a user-supplied path to the home directory.
/// Returns the input unchanged when it doesn't start with `~` (or when the
/// home directory can't be resolved).
pub fn expand_tilde(path: &str) -> String {
    if path == "~" {
        if let Some(home) = dirs::home_dir() {
            return home.to_string_lossy().to_string();
        }
    } else if let Some(rest) = path.strip_prefix("~/") {
        if let Some(home) = dirs::home_dir() {
            return home.join(rest).to_string_lossy().to_string();
        }
    }
    path.to_string()
}

/// Read `git remote get-url origin` from the workspace and parse it as a
/// GitHub slug (`owner/repo`). Returns `None` if git fails or the URL is not
/// a recognisable GitHub remote.
pub fn repo_from_workspace(workspace: &str) -> Option<String> {
    let output = std::process::Command::new("git")
        .args(["-C", workspace, "remote", "get-url", "origin"])
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let url = String::from_utf8_lossy(&output.stdout).trim().to_string();
    ninox_core::github::split_repo(&url).map(|(o, r)| format!("{o}/{r}"))
}

#[derive(Debug, Clone)]
pub struct WorkerCheckout {
    pub workspace: String,
    /// Canonical repository root used to derive `workspace`. For non-Git
    /// directories this is the supplied workspace.
    pub source_workspace: String,
    pub pooled_lease: Option<PooledCheckoutLease>,
}

impl WorkerCheckout {
    pub fn shared(workspace: String) -> Self {
        Self {
            source_workspace: workspace.clone(),
            workspace,
            pooled_lease: None,
        }
    }
}

/// Allocate a durable worker workspace.
///
/// Direct children of `repositories_root` use reusable sibling checkouts.
/// Other Git repositories use the managed-worktree root. Non-Git directories
/// retain their supplied path.
pub async fn acquire_worker_checkout_for_incarnation(
    store: Arc<Store>,
    workspace: &str,
    session_id: &str,
    incarnation_id: &str,
    repositories_root: Option<&std::path::Path>,
    worktree_root: &std::path::Path,
    inbox_enabled: bool,
) -> anyhow::Result<WorkerCheckout> {
    use anyhow::Context as _;

    let workspace = workspace.to_string();
    let session_id = session_id.to_string();
    let incarnation_id = incarnation_id.to_string();
    let repositories_root = repositories_root.map(std::path::Path::to_path_buf);
    let worktree_root = worktree_root.to_path_buf();
    let remote_repo = repo_from_workspace(&workspace);

    tokio::task::spawn_blocking(move || {
        let source_path = std::path::Path::new(&workspace);
        let identity = match ninox_core::worktree::RepositoryIdentity::resolve(source_path) {
            Ok(identity) => identity,
            Err(error) if source_path.is_dir() => {
                tracing::debug!(
                    "workspace {} is not a Git checkout; using it directly: {error}",
                    source_path.display()
                );
                return Ok(WorkerCheckout::shared(workspace));
            }
            Err(error) => return Err(error),
        };

        let canonical_repositories_root = repositories_root
            .as_deref()
            .and_then(|root| root.canonicalize().ok());
        if !identity.is_primary_checkout() {
            return Ok(WorkerCheckout::shared(
                identity.top_level.to_string_lossy().to_string(),
            ));
        }
        if ninox_core::worktree::is_pooling_eligible(
            &identity,
            canonical_repositories_root.as_deref(),
        ) {
            let lease = acquire_pooled_checkout(
                &store,
                &identity,
                PoolAcquireRequest {
                    session_id: &session_id,
                    incarnation_id: &incarnation_id,
                    branch: &session_id,
                    target: PoolAcquireTarget::Sibling,
                    inbox_enabled,
                },
            )?;
            return Ok(WorkerCheckout {
                workspace: lease.path.to_string_lossy().to_string(),
                source_workspace: identity.top_level.to_string_lossy().to_string(),
                pooled_lease: Some(lease),
            });
        }

        let managed_root = ninox_core::worktree::ManagedWorktree::pool_root(
            &identity.top_level,
            remote_repo.as_deref(),
            &worktree_root,
        )?;
        let lease = acquire_pooled_checkout(
            &store,
            &identity,
            PoolAcquireRequest {
                session_id: &session_id,
                incarnation_id: &incarnation_id,
                branch: &session_id,
                target: PoolAcquireTarget::Managed(managed_root),
                inbox_enabled,
            },
        )?;
        Ok(WorkerCheckout {
            workspace: lease.path.to_string_lossy().to_string(),
            source_workspace: identity.top_level.to_string_lossy().to_string(),
            pooled_lease: Some(lease),
        })
    })
    .await
    .context("worker checkout allocation task panicked")?
}

